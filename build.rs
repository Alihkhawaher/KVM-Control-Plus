// Build script. Two jobs:
//
//  1. Embed a timestamp, so `--version` and the About panel show exactly which
//     build is running.
//  2. Compile the Windows resources — app icon + version info — and hand the
//     .res to the linker (see build_windows_resources below).
//
// Run with `-vv` to see the build log.
use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

fn main() {
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    println!("cargo:rustc-env=BUILD_TIMESTAMP={now}");
    println!("cargo:rerun-if-changed=build.rs");

    #[cfg(target_os = "windows")]
    build_windows_resources();
}

/// Explorer's "Product name" field, and the exe name in version info.
///
/// Hard-coded rather than derived from `CARGO_PKG_NAME`: the crate is
/// `kvm-control-plus` (lowercase, hyphens) and naive capitalisation would give
/// "Kvm-control-plus". A build script cannot see the [[bin]] name either, so
/// this is the one place the display name lives on the build side.
const PRODUCT_NAME: &str = "KVM-Control Plus";
const EXE_NAME: &str = "KVM-Control-Plus.exe";

/// Compile the Windows resources — app icon + version info — and hand the .res
/// to the linker.
///
/// This deliberately drives the SDK's `rc.exe` directly instead of depending on
/// `winres` or `embed-resource`. The project's two-dependency rule is not a
/// statement about runtime only: a build dependency is still a dependency, and
/// this needs about 40 lines of std to avoid one.
///
/// If rc.exe cannot be found the build still succeeds, with a warning —
/// cosmetics must never be able to break the build.
#[cfg(target_os = "windows")]
fn build_windows_resources() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let icon = manifest.join("assets").join("icon.ico");
    println!("cargo:rerun-if-changed=assets/icon.ico");

    if !icon.exists() {
        println!(
            "cargo:warning=assets/icon.ico is missing — building without an app icon \
             (regenerate it with: python tools/make_icon.py)"
        );
        return;
    }

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));

    // Split the crate version into the four 16-bit fields VERSIONINFO wants.
    let version = env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".into());
    let mut nums = [0u32; 4];
    for (i, part) in version.split('.').take(4).enumerate() {
        let digits: String = part.chars().take_while(|c| c.is_ascii_digit()).collect();
        nums[i] = digits.parse().unwrap_or(0);
    }
    let (v0, v1, v2, v3) = (nums[0], nums[1], nums[2], nums[3]);
    let version_dotted = format!("{v0}.{v1}.{v2}.{v3}");

    let description = env::var("CARGO_PKG_DESCRIPTION").unwrap_or_default();
    let name = env::var("CARGO_PKG_NAME").unwrap_or_else(|_| "app".into());

    // rc.exe treats backslashes inside a quoted string as escapes: a path with
    // backslashes becomes one containing a literal TAB, so the resource compiler
    // then reports the icon as missing. Forward slashes are accepted by rc.exe
    // and survive quoting.
    let icon_rc = icon.display().to_string().replace('\\', "/");
    let quote_safe = |s: &str| s.replace('\\', "/").replace('"', "'");
    let (description, name) = (quote_safe(&description), quote_safe(&name));

    // Explorer shows ProductName as the app's name, so it wants "KVM-Control Plus",
    // not a whole sentence — the sentence is the FileDescription.
    let product = PRODUCT_NAME;
    let exe_name = EXE_NAME;

    let rc_text = format!(
        r#"// Generated by build.rs — do not edit; edit build.rs instead.
#define IDI_APPICON 1

IDI_APPICON ICON "{icon}"

// The version resource must carry the NUMERIC id 1. `VS_VERSION_INFO` is only a
// macro for that number in winver.h, which this script does not include, so
// writing the name here produces a resource Windows' version reader ignores
// (Get-Item .VersionInfo then comes back entirely empty).
1 VERSIONINFO
 FILEVERSION    {v0},{v1},{v2},{v3}
 PRODUCTVERSION {v0},{v1},{v2},{v3}
 FILEFLAGSMASK  0x3fL
 FILEFLAGS      0x0L
 FILEOS         0x40004L
 FILETYPE       0x1L
 FILESUBTYPE    0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "FileDescription", "{description}"
            VALUE "FileVersion",     "{version_dotted}"
            VALUE "InternalName",    "{name}"
            VALUE "OriginalFilename","{exe_name}"
            VALUE "ProductName",     "{product}"
            VALUE "ProductVersion",  "{version_dotted}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#,
        icon = icon_rc,
    );

    let rc_path = out.join("app.rc");
    if let Err(e) = fs::write(&rc_path, rc_text.as_bytes()) {
        println!("cargo:warning=could not write {rc_path:?}: {e}");
        return;
    }

    let Some(rc_exe) = find_rc_exe() else {
        println!(
            "cargo:warning=rc.exe not found (looked on PATH and in the Windows Kits) — \
             building without an embedded icon or version info"
        );
        return;
    };

    let res_path = out.join("app.res");
    // A build script has no way to say "this worked" except cargo:warning, which
    // would put a scary-looking line on every single build. Silent success is
    // right; set CONTROL3_BUILD_VERBOSE=1 to have it confirm the embedding.
    let verbose = env::var_os("CONTROL3_BUILD_VERBOSE").is_some();
    match Command::new(&rc_exe)
        .arg("/nologo")
        .arg("/fo")
        .arg(&res_path)
        .arg(&rc_path)
        .output()
    {
        Ok(o) if o.status.success() => {
            println!("cargo:rustc-link-arg={}", res_path.display());
            if verbose {
                println!(
                    "cargo:warning=embedded app icon and version info (rc.exe: {})",
                    rc_exe.display()
                );
            }
        }
        Ok(o) => {
            let err = String::from_utf8_lossy(&o.stderr);
            println!("cargo:warning=rc.exe failed, building without resources: {err}");
        }
        Err(e) => println!("cargo:warning=could not run rc.exe: {e}"),
    }
}

/// Locate `rc.exe`: PATH first (a VS developer prompt provides it), then the
/// Windows SDK's bin directory, newest version first.
#[cfg(target_os = "windows")]
fn find_rc_exe() -> Option<PathBuf> {
    if let Ok(path) = env::var("PATH") {
        for dir in env::split_paths(&path) {
            let candidate = dir.join("rc.exe");
            if candidate.is_file() {
                return Some(candidate);
            }
        }
    }

    let kits = env::var("ProgramFiles(x86)")
        .ok()
        .map(PathBuf::from)
        .or_else(|| env::var("ProgramFiles").ok().map(PathBuf::from))?;
    let bin = kits.join("Windows Kits").join("10").join("bin");
    let mut versions: Vec<PathBuf> = fs::read_dir(&bin)
        .ok()?
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.is_dir())
        .collect();
    versions.sort();
    versions.reverse();
    for v in versions {
        for arch in ["x64", "arm64", "x86"] {
            let candidate = v.join(arch).join("rc.exe");
            if candidate.is_file() {
                return Some(candidate);
            }
        }
    }
    None
}
